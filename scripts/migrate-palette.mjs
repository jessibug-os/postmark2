/**
 * One-time mechanical migration: move every source hex literal into the
 * generated swatch table, then replace numeric and CSS-string uses with typed
 * references. Embedded DOM CSS uses installed custom properties.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve, sep } from 'node:path';

const root = resolve('src');
const art = resolve('src/art');
const files = [];
const walk = (directory) => {
  for (const name of readdirSync(directory)) {
    const path = resolve(directory, name);
    if (path === art) continue;
    if (statSync(path).isDirectory()) walk(path);
    else if (path.endsWith('.ts')) files.push(path);
  }
};
walk(root);

const colors = new Set();
for (const path of files) {
  const source = readFileSync(path, 'utf8');
  for (const match of source.matchAll(/0x([0-9a-f]{6})\b/gi)) colors.add(match[1].toLowerCase());
  for (const match of source.matchAll(/#([0-9a-f]{3,8})\b/gi)) colors.add(match[1].toLowerCase());
}
const ordered = [...colors].sort();
const lines = ordered.map((color) => `  h${color}: 0x${color},`);
const cssLines = ordered.map((color) => `  h${color}: '#${color}',`);
writeFileSync(resolve(art, 'swatches.generated.ts'), `// Generated by scripts/migrate-palette.mjs.\n`
  + `// Source features import these names; raw colour literals stay in src/art only.\n`
  + `export const PALETTE_HEX = {\n${lines.join('\n')}\n} as const;\n\n`
  + `export const PALETTE_CSS = {\n${cssLines.join('\n')}\n} as const;\n`);

for (const path of files) {
  let source = readFileSync(path, 'utf8');
  const before = source;
  // Canvas APIs and texture helpers need resolved colour strings.
  source = source.replace(/(['"])#([0-9a-f]{3,8})\1/gi, (_match, _quote, color) =>
    `PALETTE_CSS.h${color.toLowerCase()}`);
  source = source.replace(/0x([0-9a-f]{6})\b/gi, (_match, color) =>
    `PALETTE_HEX.h${color.toLowerCase()}`);
  // Remaining hashes are embedded in DOM CSS strings/templates.
  source = source.replace(/#([0-9a-f]{3,8})\b/gi, (_match, color) =>
    `var(--pm-h${color.toLowerCase()})`);
  if (source === before) continue;
  let importPath = relative(dirname(path), resolve(art, 'palette')).split(sep).join('/');
  if (!importPath.startsWith('.')) importPath = `./${importPath}`;
  source = `import { PALETTE_CSS, PALETTE_HEX } from '${importPath}';\n${source}`;
  writeFileSync(path, source);
}
console.log(`Migrated ${ordered.length} swatches across ${files.length} TypeScript files.`);

