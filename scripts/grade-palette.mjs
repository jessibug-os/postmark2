/**
 * Apply the Era 1 art-direction grade once to the generated swatches.
 * Keys remain the migration-era source colour so references stay stable.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const path = resolve('src/art/swatches.generated.ts');
let source = readFileSync(path, 'utf8');
if (source.includes('ERA1_GRADED')) {
  console.log('Palette is already ERA1_GRADED.');
  process.exit(0);
}

const expand = (value) => value.length === 3
  ? value.split('').map((digit) => digit + digit).join('')
  : value;
const grade = (value) => {
  const alpha = value.length === 8 ? value.slice(6) : '';
  const rgb = expand(value.slice(0, value.length === 4 ? 3 : 6));
  const channels = [0, 2, 4].map((offset) => parseInt(rgb.slice(offset, offset + 2), 16));
  // Pull saturation toward warm paper, then age blue slightly more than red.
  const average = channels.reduce((sum, channel) => sum + channel, 0) / 3;
  const muted = channels.map((channel) => average + (channel - average) * 0.78);
  const adjusted = [
    muted[0] * 0.96 + 8,
    muted[1] * 0.93 + 7,
    muted[2] * 0.88 + 5,
  ].map((channel) => Math.max(0, Math.min(255, Math.round(channel))));
  return adjusted.map((channel) => channel.toString(16).padStart(2, '0')).join('') + alpha;
};

source = source.replace(
  /(h[0-9a-f]+:\s+0x)([0-9a-f]+)(,)/gi,
  (_match, start, value, end) => `${start}${grade(value)}${end}`,
);
source = source.replace(
  /(h[0-9a-f]+:\s+'#)([0-9a-f]+)(',)/gi,
  (_match, start, value, end) => `${start}${grade(value)}${end}`,
);
source = source.replace('// Generated by', '// ERA1_GRADED — muted, warm, aged finish.\n// Generated by');
writeFileSync(path, source);
console.log('Applied ERA1_GRADED to generated palette swatches.');

